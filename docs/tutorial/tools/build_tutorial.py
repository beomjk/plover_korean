KEY_ORDER = "12345qwertasdfg" + "xcvbnm" + "67890yuiophjkl;"


def steno_of(strokes):
    return "/".join(normalize_steno(s)[0] for s in strokes)


def keys_of_stroke(steno):
    keys = [KEYMAP[k] for k in Stroke(normalize_steno(steno)[0]).keys()]
    return " ".join(sorted(keys, key=KEY_ORDER.index))


def keys_of(strokes):
    return " → ".join(f"`{keys_of_stroke(s)}`" for s in strokes)


def check(strokes, expected):
    got = type_steno(*strokes)
    if got != expected:
        raise AssertionError(f"{'/'.join(strokes)}: expected {expected!r}, got {got!r}")


def table(rows, label=None, result="결과"):
    """rows: (spec, expected[, shown]) or, with label, (label, spec, expected[, shown])."""
    head = ([label] if label else []) + ["획", "누를 키", result]
    lines = ["| " + " | ".join(head) + " |", "|" + " --- |" * len(head)]
    for row in rows:
        row = list(row)
        name = [row.pop(0)] if label else []
        spec, expected, *shown = row
        strokes = spec.split("/")
        check(strokes, expected)
        cells = name + [f"`{steno_of(strokes)}`", keys_of(strokes), shown[0] if shown else expected]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def dict_table(rows, label="하는 일"):
    """rows: (label, steno, expected dictionary translation). For commands and keys
    whose effect is not text."""
    lines = [f"| {label} | 획 | 누를 키 |", "| --- | --- | --- |"]
    for name, steno, translation in rows:
        got = lookup(steno)
        if got != translation:
            raise AssertionError(f"{steno}: expected {translation!r}, got {got!r}")
        lines.append(f"| {name} | `{steno_of([steno])}` | {keys_of([steno])} |")
    return "\n".join(lines)


def english_keys(steno):
    keymap = english.KEYMAPS["Keyboard"]
    order = ["S-", "T-", "K-", "P-", "W-", "H-", "R-", "A-", "O-", "*", "-E", "-U",
             "-F", "-R", "-P", "-B", "-L", "-G", "-T", "-S", "-D", "-Z"]
    parsed = {"KPHRO*": ["K-", "P-", "H-", "R-", "O-", "*"],
              "PHROLG": ["P-", "H-", "R-", "O-", "-L", "-G"]}[steno]
    keys = []
    for key in sorted(parsed, key=order.index):
        bound = keymap[key]
        keys.append(bound if isinstance(bound, str) else bound[0])
    return " ".join(keys)


TO_KOREAN = "{PLOVER:SET_CONFIG:'system_name':'Korean Modern C','machine_type':'Keyboard'}"


def check_english_dictionaries():
    config = Path.home() / "Library/Application Support/plover"
    user = json.loads((config / "user.json").read_text(encoding="utf-8"))
    commands = json.loads((config / "commands.json").read_text(encoding="utf-8"))
    assert user["KPHRO*"] == TO_KOREAN
    assert commands["PHROLG"] == "{PLOVER:TOGGLE}"
    assert english_keys("KPHRO*") == "s e r f v t", english_keys("KPHRO*")
    assert english_keys("PHROLG") == "e r f v o l", english_keys("PHROLG")


