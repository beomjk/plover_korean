def layout_tables():
    physical = {v: k for k, v in KEYMAP.items() if isinstance(v, str) and k not in ("arpeggiate",)}

    def cell(key):
        name = physical[key].strip("-")
        return f"`{key}` {'`*`' if name == '*' else name}"

    left = ("| | 새끼 | 약지 | 중지 | 검지 | 검지(안쪽으로) |\n|---|---|---|---|---|---|\n"
            f"| 윗줄 | {' | '.join(cell(k) for k in 'qwert')} |\n"
            f"| 가운데 줄 | {' | '.join(cell(k) for k in 'asdfg')} |")
    thumbs = ("| | 왼쪽 | 가운데 | 오른쪽 |\n|---|---|---|---|\n"
              f"| 왼손 엄지 | {' | '.join(cell(k) for k in 'xcv')} |\n"
              f"| 오른손 엄지 | {' | '.join(cell(k) for k in 'bnm')} |")
    right = ("| | 검지(안쪽으로) | 검지 | 중지 | 약지 | 새끼 |\n|---|---|---|---|---|---|\n"
             f"| 윗줄 | {' | '.join(cell(k) for k in 'yuiop')} |\n"
             f"| 가운데 줄 | {' | '.join(cell(k) for k in 'hjkl;')} |")
    numbers = (f"| 숫자 줄 | {' | '.join(cell(k) for k in '12345')} | {' | '.join(cell(k) for k in '67890')} |\n"
               "|---|---|---|---|---|---|---|---|---|---|---|")
    return left, thumbs, right, numbers


def doc(*parts):
    return "\n\n".join(p.strip("\n") for p in parts) + "\n"


